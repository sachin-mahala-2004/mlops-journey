""" crud.py - Create, Read, Update, Delete with a Session.
Each function here uses database Session as the first argument , it never creates one . 
This makes them testable and resuable: the caller decides the transaction boundary, not the function."""
from decimal import Decimal
from sqlalchemy.orm import Session, selectinload, joinedload
from models import Course, Grade, Student, Prediction
from sqlalchemy import select,func, update,delete

#--------------------------------
# CREATE
#--------------------------------

def create_student(db:Session,name:str, email:str,
                   major:str | None=None, enrollment_year:int | None = None) -> Student:
    student = Student(name = name, email = email, major = major, enrollment_year = enrollment_year)
    db.add(student)
    db.commit()
    db.refresh(student) # repopulates with the database generated values,
    #when you db.commit() SQLAlchemy generates the student_id ,
    # but we have set created_at to server_default so that only generated by database
    return student

def create_students_bulk(db:Session, rows:list[dict]) -> int:
    if not rows :
        return 0
    db.execute(Student.__table__.insert(),rows)
    db.commit()
    return len(rows)

