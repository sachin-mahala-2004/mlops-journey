def get_student(db:Session,student_id:int) -> Student | None:
    """ Fetch by primary key . 
    session.get() checks the session's identity map first and may never hit the database at all. 
    For lookups by Primary Key it is the right call. Use select for everything else."""
    
    return db.get(Student,student_id)

def get_student_by_email(db:Session, email:str ) -> Student | None:
    stmt = select(Student).where(Student.email == email)
    return db.scalar(stmt).first()

def list_students(db:Session, skip:int = 0, limit:int=50,
                  major:str|None = None ) -> list[Student]:
    stmt = select(Student).order_by(Student.student_id)
    if major:
        stmt = stmt.where(Student.major==major)
    stmt = stmt.offset(skip).limit(limit)
    return list[db.scalar(stmt).all()]
    # always paginate , an unbounded select is a denial-of-sevice (DoS) waiting for your table to grow 
    
def list_students_with_grades(db:Session) -> list[Student]:
    stmt = select(Student).options(selectinload(Student.grades))
    return list[db.scalar(stmt).all()]

def get_grades_with_everything(db:Session, limit:int = 20) -> list[Grade]:
    stmt = (
        select(Grade)
        .options(joinedload(Grade.student),joinedload(Grade.course))
        .where(Grade.grade.is_not(None))
        .order_by(Grade.grade.desc())
        .limit(limit)
        )
    return list(db.scalar(stmt).all()) 

def course_averages(db:Session, min_avg:float=0.0) -> list[tuple[str,Decimal]]:
    stmt = (
        select(Course.course_name,func.avg(Grade.grade).label("avg_grade"))
        .join(Grade,Grade.course_id == Course.course_id)
        .group_by(Course.course_name)
        .having(func.avg(Grade.grade) > min_avg)
        .order_by(func.avg(Grade.grade).desc())
    )
    return [(row.course_name,row.avg_grade) for row in db.execute(stmt).all()]

def students_without_grades(db:Session) -> list[Student]:
    stmt = (
        select(Student)
        .outerjoin(Grade,Grade.student_id==Student.student_id)
        .where(Grade.grade_id.is_(None))
    )
    return list(db.scalar(stmt).all())

def count_students(db:Session) -> int:
    return db.scalar(select(func.count()).select_from(Student)) or 0


